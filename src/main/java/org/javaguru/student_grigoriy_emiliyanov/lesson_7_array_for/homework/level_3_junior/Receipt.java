package org.javaguru.student_grigoriy_emiliyanov.lesson_7_array_for.homework.level_3_junior;

class Receipt {
    private int number;
    private double total;

    public Receipt(int number, double total) {
        this.number = number;
        this.total = total;
    }

    public int getNumber() {
        return number;
    }

    public double getTotal() {
        return total;
    }
}
