package org.javaguru.student_aleksey_volokitin.project_5_plus_apple_warehouse.v2_optimized;

class Apple {

    private String color;
    private int weight;

    public Apple (String color, int weight) {
        this.color = color;
        this.weight = weight;
    }

    public String getColor() {
        return color;
    }

    public int getWeight() {
        return weight;
    }

}
