package org.javaguru.student_elena_tiutiunnikova.project_5_apple_warehouse;

class Apple {
    private String colour;
    private int wheith;

    public Apple(String colour, int wheith) {
        this.colour = colour;
        this.wheith = wheith;
    }

    public int getWheith() {
        return wheith;
    }

    public String getColour() {
        return colour;
    }
}
